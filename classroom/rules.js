const ITEMS = {
  jump: { label: '立定跳远', unit: '米', hint: '如 2.41', short: '跳远' },
  ball: { label: '掷实心球', unit: '米', hint: '如 9.60', short: '实心球' },
  run: { label: '耐久跑', short: '耐久跑' },
  weight: { label: '身高标准体重', short: '身高体重' },
};
const ITEM_KEYS = Object.keys(ITEMS);
const SEX = { m: '男生', f: '女生' };

function itemLabel(item, sex) {
  return item === 'run' ? (sex === 'm' ? '1000 米跑' : '800 米跑') : ITEMS[item].label;
}

function grade(score) {
  return score >= 90 ? 'A' : score >= 75 ? 'B' : score >= 60 ? 'C' : 'D';
}

function physicalScore(item, sex, value) {
  const index = RULES.physical[sex][item].findIndex((threshold) =>
    item === 'run' ? value <= threshold : value >= threshold
  );
  return index < 0 ? 0 : RULES.scores[index];
}

function weightScore(sex, height, mass) {
  const { min, rows } = RULES.weight[sex];
  const heightBand = Math.floor(Math.round(height * 10) / 10);
  const tableBand = Math.min(Math.max(heightBand, min), min + rows.length - 1);
  const difference = tableBand - heightBand;
  const adjustedMass = Math.round(mass * 10) + difference * (difference > 0 ? 5 : 9);
  const category = rows[tableBand - min].filter((cut) => adjustedMass >= cut).length;
  return {
    score: [50, 60, 100, 60, 50][category],
    category: ['营养不良', '较低体重', '正常体重', '超重', '肥胖'][category],
    shifted: difference !== 0,
  };
}

function compositeScore(scores) {
  return (3 * (scores.jump + scores.ball + scores.run) + scores.weight) / 10;
}
